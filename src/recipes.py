def match_recipe(brief: str) -> Optional[dict]:
    """briefの文中から業種レシピを1件選ぶ。複数当たったら一致キーワードの合計文字数が多い方
    （「動物病院」(4字)が「病院」(2字)に勝つ＝具体的な語を持つレシピを優先）。"""
    if not brief:
        return None
    best, best_score = None, 0
    for r in RECIPES:
        score = sum(len(k) for k in r["keys"] if k.lower() in brief.lower())
        if score > best_score:
            best, best_score = r, score
    if best:
        log.info("業種レシピ適用: %s", best["name"])
    return best


def recipe_prompt_block(brief: str) -> str:
    """briefに合うレシピをプロンプト用の文にする。該当なしなら空文字。"""
    r = match_recipe(brief)
    if not r:
        return ""
    return (
        f"【業種の勘所：{r['name']}（プロの判断基準・必ず反映）】\n"
        f"{r['text']}\n"
        "※手本サイトのレイアウト・配色トークンと矛盾したら、レイアウトは手本を優先し、"
        "写真の選び方・コピーの書き方・導線設計はこの勘所を優先する。\n"
    )
